# 6. CALCULAR mx ----
# ------------------------------------------------------------------------------

tv[, mx := deaths / N]
tv[is.na(mx), mx := 0]
tv[is.infinite(mx), mx := 0]

# ------------------------------------------------------------------------------
# 7. DEFINIR ax ----
# ------------------------------------------------------------------------------

tv[, ax := 0.5]

# ------------------------------------------------------------------------------
# 8. CALCULAR qx ----
# ------------------------------------------------------------------------------

tv[, qx := mx / (1 + (1 - ax) * mx)]
tv[qx > 1, qx := 1]

# Último grupo abierto
tv[age == max(age), qx := 1]

# ------------------------------------------------------------------------------
# 9. ORDENAR ----
# ------------------------------------------------------------------------------

setorder(tv, year, sex, age)

# ------------------------------------------------------------------------------
# 10. CREAR VARIABLES ----
# ------------------------------------------------------------------------------

tv[, lx := NA_real_]
tv[, dx := NA_real_]
tv[, Lx := NA_real_]
tv[, Tx := NA_real_]
tv[, ex := NA_real_]

# ------------------------------------------------------------------------------
# 11. CONSTRUIR TABLAS DE VIDA ----
# ------------------------------------------------------------------------------

years <- unique(tv$year)
sexes <- unique(tv$sex)

for(y in years){
  
  for(s in sexes){
    
    temp <- copy(tv[year == y & sex == s])
    
    if(nrow(temp) == 0) next
    
    # --------------------------------------------------------------------------
    # lx
    # --------------------------------------------------------------------------
    
    temp$lx[1] <- 100000
    
    for(i in 2:nrow(temp)){
      
      temp$lx[i] <- temp$lx[i-1] * (1 - temp$qx[i-1])
    }
    
    # --------------------------------------------------------------------------
    # dx
    # --------------------------------------------------------------------------
    
    temp$dx <- temp$lx * temp$qx
    
    # --------------------------------------------------------------------------
    # Lx
    # --------------------------------------------------------------------------
    
    for(i in 1:(nrow(temp)-1)){
      
      temp$Lx[i] <- temp$lx[i+1] + temp$ax[i] * temp$dx[i]
    }
    
    # Último grupo abierto
    ultimo <- nrow(temp)
    
    temp$Lx[ultimo] <- temp$lx[ultimo] / temp$mx[ultimo]
    
    # --------------------------------------------------------------------------
    # Tx
    # --------------------------------------------------------------------------
    
    temp$Tx <- rev(cumsum(rev(temp$Lx)))
    
    # --------------------------------------------------------------------------
    # ex
    # --------------------------------------------------------------------------
    
    temp$ex <- temp$Tx / temp$lx
    
    # --------------------------------------------------------------------------
    # GUARDAR
    # --------------------------------------------------------------------------
    
    tv[year == y & sex == s] <- temp
  }
}

# ------------------------------------------------------------------------------
# 12. REDONDEAR RESULTADOS ----
# ------------------------------------------------------------------------------

tv[, mx := round(mx, 6)]
tv[, qx := round(qx, 6)]
tv[, lx := round(lx, 0)]
tv[, dx := round(dx, 0)]
tv[, Lx := round(Lx, 0)]
tv[, Tx := round(Tx, 0)]
tv[, ex := round(ex, 2)]

# ------------------------------------------------------------------------------
# 13. GUARDAR TABLAS DE VIDA ----
# ------------------------------------------------------------------------------

write.csv(
  tv,
