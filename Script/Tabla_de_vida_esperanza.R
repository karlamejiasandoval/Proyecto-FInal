library(data.table)
library(dplyr)
library(tidyr)
library(DT)

# ------------------------------------------------------------------------------
# 2. CARGAR DATOS ----
# ------------------------------------------------------------------------------

apv <- fread("Data/apv.csv")
def <- fread("Data/def_pro.csv")

# ------------------------------------------------------------------------------
# 3. HOMOLOGAR SEXOS ----
# ------------------------------------------------------------------------------

apv$sex <- tolower(apv$sex)
def$sex <- tolower(def$sex)

# Convertir a M y F
apv$sex[apv$sex == "male"] <- "M"
apv$sex[apv$sex == "female"] <- "F"

def$sex[def$sex == "male"] <- "M"
def$sex[def$sex == "female"] <- "F"

# ------------------------------------------------------------------------------
# 4. UNIR BASES ----
# ------------------------------------------------------------------------------

tv <- merge(
  apv,
  def,
  by = c("year", "age", "sex"),
  all.x = TRUE
)

