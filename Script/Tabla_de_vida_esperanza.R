apv <- fread("Data/apv.csv")
def <- fread("Data/def_pro.csv")

# ------------------------------------------------------------------------------
# 3. HOMOLOGAR SEXOS ----
# ------------------------------------------------------------------------------

apv$sex <- tolower(apv$sex)
def$sex <- tolower(def$sex)

# ------------------------------------------------------------------------------
# 4. UNIR BASES ----
# ------------------------------------------------------------------------------

tv <- merge(
  apv,
  def,
  by = c("year", "age", "sex"),
  all.x = TRUE
)

